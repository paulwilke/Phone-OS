def test_check_mode():
    with tempfile.TemporaryDirectory() as tmpdir:
        # Populate the directory with the correct outputs
        rc = gen_config.run(TINY, tmpdir, check_mode=False)
        check("generate to tmpdir exits 0", rc == 0)

        # --check should pass
        rc = gen_config.run(TINY, tmpdir, check_mode=True)
        check("--check passes on up-to-date", rc == 0)

        # Corrupt one file
        cpp_path = os.path.join(tmpdir, "src", "config", "schema_generated.h")
        with open(cpp_path, "a") as f:
            f.write("// corrupted\n")
        rc = gen_config.run(TINY, tmpdir, check_mode=True)
        check("--check fails on stale file", rc != 0)

        # Remove a file
        os.unlink(cpp_path)
        rc = gen_config.run(TINY, tmpdir, check_mode=True)
        check("--check fails on missing file", rc != 0)


