#!/usr/bin/env python3
"""Tests for scripts/gen_config.py.

Run with:  python3 test/test_schema_gen/test_gen.py

Tests:
  1. Golden output for a tiny schema: the generator produces the expected C++ header,
     form JSON, docs and example file.
  2. A schema with an unknown type is refused with a reason.
  3. A schema with a missing required field is refused with a reason.
  4. --check detects an out-of-date file.
  5. --check passes when all files are up to date.
  6. A default entry of a list section reaches every output and is checked; the checkbox widget is only for a bool.
"""
import json
import os
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, "scripts"))
import gen_config  # noqa: E402

TINY = os.path.join(os.path.dirname(__file__), "tiny_schema.toml")

TESTS_PASSED = 0
TESTS_FAILED = 0


def check(name, condition, detail=""):
    global TESTS_PASSED, TESTS_FAILED
    if condition:
        print(f"  PASS  {name}")
        TESTS_PASSED += 1
    else:
        print(f"  FAIL  {name}" + (f": {detail}" if detail else ""))
        TESTS_FAILED += 1


def tiny_outputs():
    files, sections, keys = gen_config.load_schema(TINY)
    return gen_config.all_outputs(files, sections, keys, REPO)


# ---------------------------------------------------------------------------
# 1. Golden output checks
# ---------------------------------------------------------------------------

def test_golden_cpp():
    out = tiny_outputs()
    cpp = out["src/config/schema_generated.h"]
    check("cpp: #pragma once",       "#pragma once" in cpp)
    check("cpp: namespace config",   "namespace config {" in cpp)
    check("cpp: kKeys array",        "kKeys[]" in cpp)
    check("cpp: kSections array",    "kSections[]" in cpp)
    check("cpp: childName entry",    '"childName"' in cpp)
    check("cpp: KeyType::String",    "KeyType::String" in cpp)
    check("cpp: KeyType::Integer",   "KeyType::Integer" in cpp)
    check("cpp: Apply::Immediate",   "Apply::Immediate" in cpp)
    check("cpp: list=true for tags", '"tags", true,' in cpp or '"tags",\n     true,' in cpp
          or ',"tags", true,' in cpp)
    check("cpp: generated notice",   "Generated by scripts/gen_config.py" in cpp)


def test_golden_json():
    out = tiny_outputs()
    form = json.loads(out["config/form_generated.json"])
    check("json: settings file",       "settings" in form["files"])
    sec_names = [s["id"] for s in form["files"]["settings"]["sections"]]
    check("json: child section",       "child" in sec_names)
    check("json: tags section",        "tags" in sec_names)
    tags_sec = next(s for s in form["files"]["settings"]["sections"] if s["id"] == "tags")
    check("json: tags is list",        tags_sec["list"] is True)
    child_sec = next(s for s in form["files"]["settings"]["sections"] if s["id"] == "child")
    child_keys = [k["name"] for k in child_sec["keys"]]
    check("json: name key",            "name" in child_keys)
    check("json: age key",             "age" in child_keys)
    age_key = next(k for k in child_sec["keys"] if k["name"] == "age")
    check("json: age min_val = 0",     age_key["min_val"] == 0)
    check("json: age max_val = 17",    age_key["max_val"] == 17)
    check("json: age apply immediate", age_key["apply"] == "immediate")


def test_golden_docs():
    out = tiny_outputs()
    docs = out["docs/configuration-reference.md"]
    check("docs: title",              "# Configuration reference" in docs)
    check("docs: generated notice",   "Generated by scripts/gen_config.py" in docs)
    check("docs: settings path",      "/config/settings.toml" in docs)
    check("docs: child section",      "[child]" in docs)
    check("docs: tags list section",  "[[tags]]" in docs)
    check("docs: name key row",       "| `name` |" in docs)
    check("docs: integer range",      "0–17" in docs)  # en-dash in the generated range


def test_golden_example():
    out = tiny_outputs()
    example = out["config/examples/settings.toml"]
    check("example: header comment",  "/config/settings.toml" in example)
    check("example: [child] section", "[child]" in example)
    check("example: name = ",         "name = " in example)
    check("example: age = ",          "age = " in example)


# ---------------------------------------------------------------------------
# 2. Bad schema: unknown type
# ---------------------------------------------------------------------------

def test_unknown_type():
    import tomllib, io
    bad_schema = b'''
[[file]]
id = "s"
path = "/config/s.toml"
example = "config/examples/s.toml"
label = "s.label"

[[key]]
file = "s"
section = ""
name = "x"
type = "badtype"
default = ""
label = "s.x.label"
help = "s.x.help"
field = ""
apply = "restart"
secret = false
required = false
'''
    import tempfile, os
    with tempfile.NamedTemporaryFile(suffix=".toml", delete=False) as f:
        f.write(bad_schema)
        tmp = f.name
    try:
        files, sections, keys = gen_config.load_schema(tmp)
        errors = gen_config.validate_schema(files, sections, keys)
        check("bad type refused",    any("badtype" in e for e in errors),
              f"errors = {errors}")
        check("bad type has reason", any("unknown type" in e for e in errors))
    finally:
        os.unlink(tmp)


