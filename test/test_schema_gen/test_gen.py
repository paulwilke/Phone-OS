# 2. Bad schema: unknown type
# ---------------------------------------------------------------------------

def test_unknown_type():
    import tomllib, io
    bad_schema = b'''
[[file]]
id = "s"
path = "/config/s.toml"
example = "config/examples/s.toml"
label = "s.label"

[[key]]
file = "s"
section = ""
name = "x"
type = "badtype"
default = ""
label = "s.x.label"
help = "s.x.help"
field = ""
apply = "restart"
secret = false
required = false
'''
    import tempfile, os
    with tempfile.NamedTemporaryFile(suffix=".toml", delete=False) as f:
        f.write(bad_schema)
        tmp = f.name
    try:
        files, sections, keys, _ = gen_config.load_schema(tmp)
        errors = gen_config.validate_schema(files, sections, keys)
        check("bad type refused",    any("badtype" in e for e in errors),
              f"errors = {errors}")
        check("bad type has reason", any("unknown type" in e for e in errors))
    finally:
        os.unlink(tmp)


