#!/usr/bin/env python3
"""Writes src/drivers/ApnTable.cpp, the list of operators and their APNs, from the Android Open Source Project's
sample APN file (Apache-2.0).

    scripts/gen_apn_table.py --source apns-full-conf.xml    # regenerate the list from the file
    scripts/gen_apn_table.py --check                        # the stored list is well formed (no file needed)
    scripts/gen_apn_table.py --check --source <file>        # ... and is what that file gives

The file is `device/sample/etc/apns-full-conf.xml` of https://android.googlesource.com/device/sample. It is
read as data only. For every operator (MCC and MNC) the first entry of the file is taken that

  * is for the plain network, not for a virtual operator on it (no `mvno_type`),
  * carries the type `default` (the internet bearer),
  * has an APN of letters, digits, dots, hyphens and underscores, at most 100 characters (what the driver
    accepts, see A7682EDriver::apnUsable),
  * is not a test network (MCC 001).

The result is sorted by MCC, MNC and the number of MNC digits, so that the driver can search it in halves. Decision
D-9 in docs/decisions.md; the module is described in docs/apn-table.md.
"""
import argparse
import hashlib
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "drivers", "ApnTable.cpp")
SOURCE_URL = "https://android.googlesource.com/device/sample/+/refs/heads/main/etc/apns-full-conf.xml"
APN_RE = re.compile(r"^[A-Za-z0-9._-]{1,100}$")
LICENCE = """// Derived from the Android Open Source Project's sample APN file, Copyright 2006, The Android Open Source Project,
// Licensed under the Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0). The facts used are the
// pairs of operator code and APN name; the file is described in THIRD_PARTY.md."""


def entries_from(path):
    """The (mcc, mnc, mnc digits, apn) rows the rules above pick, in file order, one per operator."""
    root = ET.parse(path).getroot()
    seen, rows = set(), []
    for a in root.iter("apn"):
        mcc, mnc, apn = a.get("mcc", ""), a.get("mnc", ""), a.get("apn", "")
        if not (re.fullmatch(r"\d{3}", mcc) and re.fullmatch(r"\d{2,3}", mnc)) or mcc == "001":
            continue
        if a.get("mvno_type") or "default" not in [t.strip() for t in a.get("type", "").split(",")]:
            continue
        if not APN_RE.match(apn) or (int(mcc), int(mnc), len(mnc)) in seen:
            continue
        seen.add((int(mcc), int(mnc), len(mnc)))
        rows.append((int(mcc), int(mnc), len(mnc), apn))
    rows.sort()
    return rows


def render(rows, sha256):
    lines = ["// Generated by scripts/gen_apn_table.py; do not edit.", LICENCE,
             f"// Source: {SOURCE_URL}", f"// sha256 of the source file: {sha256}",
             f"// Entries: {len(rows)}", "", '#include "ApnTable.h"', "", "namespace apn {", "",
             f'const char* const kSourceSha256 = "{sha256}";', "", "const Entry kTable[] = {"]
    lines += [f'    {{{mcc}, {mnc}, {digits}, "{name}"}},' for mcc, mnc, digits, name in rows]
    lines += ["};", "", f"const size_t kTableSize = {len(rows)};", "", "}  // namespace apn", ""]
    return "\n".join(lines)


def parse_stored(text):
    """The rows and the sha256 of a stored ApnTable.cpp, or None when it is not in the format of render()."""
    m = re.search(r'kSourceSha256 = "([0-9a-f]{64})"', text)
    rows = [(int(a), int(b), int(c), d) for a, b, c, d in re.findall(r'^    \{(\d+), (\d+), (\d), "([^"]*)"\},$', text, re.M)]
    count = re.search(r"kTableSize = (\d+);", text)
    if not m or not count or int(count.group(1)) != len(rows):
        return None
    return rows, m.group(1)


def check_stored(text):
    """Problems with a stored list: the format, the order, duplicates, MNC digits, APN characters."""
    parsed = parse_stored(text)
    if parsed is None:
        return ["src/drivers/ApnTable.cpp: not in the format of scripts/gen_apn_table.py"]
    rows, _ = parsed
    problems = []
    if not rows:
        problems.append("the list is empty")
    if rows != sorted(set(rows)):
        problems.append("the list is not sorted or has an operator twice")
    for mcc, mnc, digits, name in rows:
        if not (100 <= mcc <= 999) or mcc == 1 or digits not in (2, 3) or mnc >= 10 ** digits or not APN_RE.match(name):
            problems.append(f"bad entry {mcc} {mnc:0{digits}d} {name!r}")
    return problems


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--source", help="apns-full-conf.xml of the Android Open Source Project")
    ap.add_argument("--check", action="store_true", help="fail when the stored list is not well formed (or is not what --source gives)")
    ap.add_argument("--out", default=OUT, help="the file to write or check (for tests)")
    args = ap.parse_args()

    stored = open(args.out, encoding="utf-8").read() if os.path.exists(args.out) else ""
    if args.check:
        problems = check_stored(stored) if stored else [f"{args.out}: does not exist"]
        if args.source and not problems:
            sha = hashlib.sha256(open(args.source, "rb").read()).hexdigest()
            if render(entries_from(args.source), sha) != stored:
                problems.append("the stored list is not what the source file gives; run scripts/gen_apn_table.py --source")
        for p in problems:
            print(p, file=sys.stderr)
        if not problems:
            print(f"gen_apn_table --check: {len(parse_stored(stored)[0])} operators, well formed")
        return 1 if problems else 0
    if not args.source:
        ap.error("--source is needed to write the list")
    sha = hashlib.sha256(open(args.source, "rb").read()).hexdigest()
    rows = entries_from(args.source)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(render(rows, sha))
    print(f"wrote {args.out}: {len(rows)} operators")
    return 0


if __name__ == "__main__":
    sys.exit(main())
