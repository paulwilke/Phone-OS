#!/usr/bin/env python3
"""Generates device/ShippedAssets.h: the shipped language catalogs and the version as C++ data.

    scripts/gen_device_assets.py           # writes the file
    scripts/gen_device_assets.py --check   # exits 1 when the file is not current (CI)

The firmware carries lang/*.toml, lang/web/*.toml and VERSION as data. They cannot go through PlatformIO's
embed_txtfiles, which names its objects after the file name alone and so cannot tell lang/en.toml from
lang/web/en.toml. The simulator reads the same files from disk; there is one source of each.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "device", "ShippedAssets.h")
DELIM = "phone_os_toml"


def sources():
    out = []
    for sub, prefix in (("lang", "kLang"), ("lang/web", "kWeb")):
        directory = os.path.join(ROOT, sub)
        for name in sorted(os.listdir(directory)):
            if name.endswith(".toml"):
                out.append((prefix + name[:-5].capitalize().replace("-", "_"), os.path.join(directory, name)))
    return out


def render():
    lines = [
        "// Generated by scripts/gen_device_assets.py from lang/*.toml, lang/web/*.toml and VERSION. Do not edit.",
        "// allow-non-english: holds the catalogs of every language.",
        "#pragma once",
        "",
        "#include <string_view>",
        "",
        "namespace shipped {",
        "",
    ]
    for symbol, path in sources():
        text = open(path, encoding="utf-8").read()
        assert f"){DELIM}\"" not in text, path
        lines.append(f"constexpr std::string_view {symbol}(R\"{DELIM}({text}){DELIM}\");")
        lines.append("")
    version = open(os.path.join(ROOT, "VERSION"), encoding="utf-8").read().strip()
    lines.append(f"constexpr std::string_view kVersion(\"{version}\");")
    lines.append("")
    lines.append("}  // namespace shipped")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("device/ShippedAssets.h is not current: run scripts/gen_device_assets.py")
            return 1
        print("gen_device_assets --check: up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
